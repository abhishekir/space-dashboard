const parse = (csv) =>
  csv.trim().split('\n').map((line) => {
    const [d, x, y, z] = line.split(',');
    return { t: `${d}T00:00:00.000Z`, x: Number(x), y: Number(y), z: Number(z) };
  });

const mag = (p) => Math.hypot(p.x, p.y, p.z);
const L2_RATIO = 0.0100038;

const jwstArc = parse(JWST);
const romanArc = parse(ROMAN);
const sunArc = parse(SUN);

const sunNow = sunArc[sunArc.length - 1];
const sunR = mag(sunNow);
const l2d = sunR * L2_RATIO;
const l2 = {
  x: (-sunNow.x / sunR) * l2d,
  y: (-sunNow.y / sunR) * l2d,
  z: (-sunNow.z / sunR) * l2d,
  distance: l2d,
};

// Nearest sample to the seed capture date.
const at = (arc, iso) =>
  arc.reduce((b, p) =>
    Math.abs(new Date(p.t) - new Date(iso)) < Math.abs(new Date(b.t) - new Date(iso)) ? p : b);

const jwstNow = at(jwstArc, '2026-09-20');
const romanNow = at(romanArc, '2026-09-20');
const toL2 = (p) => Math.hypot(p.x - l2.x, p.y - l2.y, p.z - l2.z);

const payload = {
  generatedAt: '2026-09-20T08:00:00.000Z',
  seeded: true,
  frame: 'Ecliptic of J2000.0, geocentric (Horizons CENTER=500@399)',
  units: 'km',
  sun: { ...sunNow, distance: sunR },
  l2,
  bodies: {
    jwst: {
      label: 'James Webb Space Telescope',
      naifId: '-170',
      position: jwstNow,
      rangeFromEarth: mag(jwstNow),
      rangeFromL2: toL2(jwstNow),
      phase: 'operational',
      arc: jwstArc,
      coverage: { notBefore: null, notAfter: '2031-Sep-06 23:59' },
    },
    roman: {
      label: 'Nancy Grace Roman Space Telescope',
      naifId: '-211',
      position: romanNow,
      rangeFromEarth: mag(romanNow),
      rangeFromL2: toL2(romanNow),
      phase: toL2(romanNow) < 4e5 ? 'operational' : 'cruise',
      cruiseProgress: Math.min(1, mag(romanNow) / l2d),
      arc: romanArc,
      coverage: { notBefore: '2026-Aug-30 11:59:09', notAfter: '2026-Oct-12 12:58' },
      arcClamped: true,
    },
  },
  sunArc,
};

const OUT = resolve(ROOT, 'public/data/telescopes.json');
await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, JSON.stringify(payload, null, 2));
